public class K18_WhileLoopÇarpım {
    public static void main(String[] args) {
   //20 ila 30 arasındaki çift sayıların çarpımı
   int başlangıçSayı=20;
   int çarpım=1;
   while (başlangıçSayı<=30){

       if (başlangıçSayı%2==0){
           çarpım*=başlangıçSayı;



       }
       başlangıçSayı++;


   }
        System.out.println("while loop ile 20 30 arası sayıların çarpımı "+çarpım);




















    }
























}
